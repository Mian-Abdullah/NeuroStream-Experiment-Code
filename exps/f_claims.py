"""Writes docs/CLAIMS_TABLE.md: every number macro used in the paper -> value -> result file -> producing script,
plus the paper locations where it appears. Usage: python exps/f_claims.py"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = [  # (regex on macro name, result file, producing script)
    (r"^Sfail|^Sspoof", "results/S_fail/*.json", "exps/s2_sweeps.py"),
    (r"^Sflood|^Ssupp|^FloodOne", "results/S_attack/byz_*.json", "exps/s2_sweeps.py"),
    (r"^Svt", "results/S_privacy/svt_0.2_1.json (+ results/P/accounting.json for SvtEpsRun)", "exps/s2_sweeps.py, exps/p1_accounting.py"),
    (r"^Curve|^Kten|^Kfour|^MagLow", "results/S_sweeps/theta_curve.json, K_*.json, mag_*.json", "exps/s2_sweeps.py"),
    (r"^Nonlin", "results/S_fail/nonlinear.json", "exps/s2_sweeps.py"),
    (r"^Wcal|^Weq", "results/S/weights_*.json", "exps/s1_main.py"),
    (r"^S", "results/S/main_outage_drift.json, tuning.json", "exps/s1_main.py"),
    (r"^Leg", "results/legacy/exp_a.json", "exps/legacy/exp_a_bound.py"),
    (r"^T", "results/T/theory.json", "exps/t1_theory.py"),
    (r"^Acc|^Hor|^Gate|^Pf", "results/P/accounting.json", "exps/p1_accounting.py"),
    (r"^Dp", "results/P/dp_utility.json", "exps/p2_b1_fl.py p2"),
    (r"^Cm", "results/B_real/cmapss.json", "exps/c1_cmapss.py"),
    (r"^(Cov|Air)Cl|^ClAcc", "results/A/closed_<dataset>_K50.json", "exps/a2_closed_loop.py"),
    (r"^A|^ElecRec", "results/A/open_<dataset>_K<K>.json", "exps/a1_open_loop.py"),
    (r"^Byz", "results/B/byzantine.json", "exps/p2_b1_fl.py b1"),
    (r"^(Rows|Feat|Bytes|Eng)", "results/data_provenance.json", "exps/d0_provenance.py"),
    (r"^RuntimeHours", "results/**/*.json (runtime_s fields)", "exps/f_numbers.py"),
]


def main():
    nums = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}", open(os.path.join(ROOT, "paper", "numbers.tex")).read()))
    tex = {f: open(os.path.join(ROOT, "paper", f)).read() for f in ["main.tex", "appendix.tex"]}
    secs = {}
    for f, t in tex.items():
        cur = "front matter"
        for line in t.splitlines():
            m = re.search(r"\\(sub)?section\*?\{([^}]*)\}", line)
            if m:
                cur = m.group(2)
            for k in re.findall(r"\\([A-Za-z]+)", line):
                if k in nums:
                    secs.setdefault(k, set()).add(f"{f.replace('.tex','')}: {cur}")
    L = ["# CLAIMS_TABLE.md (generated by exps/f_claims.py)", "",
         "Every number in the paper's text is a macro in `paper/numbers.tex`, emitted by `exps/f_numbers.py` from the result",
         "files below. Tables in `paper/tables/*.tex` are emitted by the same script from the same files. Figures are",
         "emitted by `exps/f_figures.py` from the files named in their captions. Unused macros are listed with location \"-\".",
         "", "| macro | value | result file | producing script | used in |", "|---|---|---|---|---|"]
    for k in sorted(nums):
        src = next(((f, s) for r, f, s in SRC if re.search(r, k)), ("?", "?"))
        v = nums[k].replace("|", "/")
        L.append(f"| `\\{k}` | {v} | {src[0]} | {src[1]} | {'; '.join(sorted(secs.get(k, {'-'})))} |")
    L += ["", "## Figures", "",
          "| figure | data | script |", "|---|---|---|",
          "| Fig. 1 | seeded re-run of Track S (seed 3), series saved to results/figs_data/fig1.json | exps/f_figures.py |",
          "| Fig. 2 | results/legacy/exp_a.json, results/T/theory.json | exps/f_figures.py |",
          "| Fig. 3 | results/S_sweeps/theta_curve.json, results/S_fail/zobs_*.json, zsd_*.json | exps/f_figures.py |",
          "| Fig. 4 | results/A/open_*.json | exps/f_figures.py |",
          "| Fig. 5 | results/P/accounting.json, results/B/byzantine.json | exps/f_figures.py |",
          "", "## Tables", "", "| table | data | script |", "|---|---|---|",
          "| Tab. 3 (sim main) | results/S/main_outage_drift.json, tuning.json | exps/f_numbers.py |",
          "| Tab. 4 (failure/attacks) | results/S_fail, results/S_attack | exps/f_numbers.py |",
          "| Tab. 5 (real, open loop) | results/A/open_*.json | exps/f_numbers.py |",
          "| Tab. 6 (real, closed loop) | results/A/closed_*.json | exps/f_numbers.py |",
          "| Tab. 7 (C-MAPSS) | results/B_real/cmapss.json | exps/f_numbers.py |",
          "| App. tables | results/S_sweeps, results/S/weights_*, results/P/*, results/B/byzantine.json | exps/f_numbers.py |"]
    open(os.path.join(ROOT, "docs", "CLAIMS_TABLE.md"), "w").write("\n".join(L) + "\n")
    unknown = [k for k in nums if not any(re.search(r, k) for r, _, _ in SRC)]
    print(len(nums), "macros; unmapped:", unknown)


if __name__ == "__main__":
    main()
