"""Dataset provenance: sizes, checksums, shapes and mirror commits -> results/data_provenance.json, data/PROVENANCE.md"""
import hashlib, json, os, sys
import pandas as pd
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ns import data, runner
RAW = data.RAW
MIRROR = {"streaming": ("https://github.com/scikit-multiflow/streaming-datasets", "f1eb9f068c3450233721c3beac6fb0e880e9e7d7"),
          "cmapss": ("https://github.com/edwardzjl/CMAPSSData", "ed40e40e38f95fcfb84a8f48972a3f22a46fbb1d")}
out = {"retrieved": "2026-11-19", "mirrors": MIRROR, "files": {}, "datasets": {}}
for root, _, fs in os.walk(RAW):
    for f in sorted(fs):
        if f.endswith((".csv", ".txt")):
            p = os.path.join(root, f)
            out["files"][os.path.relpath(p, RAW)] = dict(bytes=os.path.getsize(p), sha256=hashlib.sha256(open(p, "rb").read()).hexdigest())
for name in ["elec", "covtype", "airlines"]:
    X, y, g, meta = data.load(name)
    out["datasets"][name] = dict(rows=int(X.shape[0]), features_used=int(X.shape[1]), classes=int(y.max() + 1))
cm = sum(v["bytes"] for k, v in out["files"].items() if k.startswith("cmapss/") and k.endswith(".txt") and "readme" not in k)
for fd in ["FD002", "FD004"]:
    d = pd.read_csv(os.path.join(RAW, "cmapss", f"train_{fd}.txt"), sep=r"\s+", header=None)
    out["datasets"][f"cmapss_{fd}"] = dict(rows=int(len(d)), columns=int(d.shape[1]), engines=int(d[0].nunique()))
out["cmapss_all_12_files_bytes"] = cm
json.dump(out, open(os.path.join(runner.RESULTS, "data_provenance.json"), "w"), indent=1)
L = ["# Data provenance (generated by exps/d0_provenance.py)", "", f"Retrieved {out['retrieved']} from GitHub mirrors (official hosts were unreachable from the build sandbox).", ""]
for k, (u, c) in MIRROR.items():
    L.append(f"- mirror `{k}`: {u} at commit `{c}`")
L += ["", "| file | bytes | sha256 |", "|---|---|---|"] + [f"| {k} | {v['bytes']:,} | `{v['sha256']}` |" for k, v in out["files"].items()]
L += ["", "| dataset | rows | features used / columns | classes / engines |", "|---|---|---|---|"]
for k, v in out["datasets"].items():
    L.append(f"| {k} | {v['rows']:,} | {v.get('features_used', v.get('columns'))} | {v.get('classes', v.get('engines'))} |")
L += ["", f"C-MAPSS, all 12 text files: {cm:,} bytes.",
      "", "Official sources to cross-check before submission: Elec2 (MOA / Harries 1999), Covertype (UCI ML Repository),",
      "Airlines (MOA / Ikonomovska), C-MAPSS (NASA PCoE / data.nasa.gov). Licences: [VERIFY] for each.",
      "Intel Berkeley Lab data (db.csail.mit.edu/labdata) could not be retrieved from the sandbox and is NOT used."]
open(os.path.join(os.path.dirname(runner.RESULTS), "data", "PROVENANCE.md"), "w").write("\n".join(L) + "\n")
print(json.dumps(out["datasets"]), cm)
